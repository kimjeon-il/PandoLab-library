import assert from 'node:assert/strict';
import {randomBytes,createHash} from 'node:crypto';
import {copyFileSync,mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {createServer} from 'node:net';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const {runNativeBridge}=await import(pathToFileURL(resolve('tools/qgis/native-bridge.mjs')));
const root=mkdtempSync(resolve('build-native/qgis/edit-proof-'));
const listener=createServer();await new Promise((ok,fail)=>listener.once('error',fail).listen(0,'127.0.0.1',ok));
const port=listener.address().port;await new Promise((ok,fail)=>listener.close(error=>error?fail(error):ok()));
const config={host:'127.0.0.1',port,token:randomBytes(32).toString('hex'),qgisRoot:'D:/dev/tools/osgeo4w',
  profilesRoot:join(root,'profiles'),profile:'proof',artifactDirectory:resolve(process.env.PANDO_QGIS_TEST_ARTIFACT)};
const configPath=join(root,'qgis-config.json');writeFileSync(configPath,JSON.stringify(config),{flag:'wx'});
const command=(...args)=>runNativeBridge(['--config',configPath,...args]);
const started=await command('start');console.log(JSON.stringify({stage:'start',root,pid:started.pid}));
const original=resolve(process.env.TEMP,'pando-qgis-migration-hJqtBq','source.geojson');
const input=join(root,'editable.geojson');copyFileSync(original,input);
const digest=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const inputHash=digest(input),originalHash=digest(original);
const opened=await command('open',input),layer=opened.id;
assert.equal(opened.feature_count,2);
await assert.rejects(command('set-attribute','--layer',layer,'--fid','0','--field','name','--json',JSON.stringify('edited')),/edit session/i);
await command('begin-edit','--layer',layer);
await assert.rejects(command('begin-edit','--layer',layer),/existing edit session/i);
await command('set-attribute','--layer',layer,'--fid','0','--field','name','--json',JSON.stringify('편집 검증'));
await command('undo-edit','--layer',layer);
const undone=join(root,'undone.geojson');await command('export','--layer',layer,'--output',undone);
assert.equal(JSON.parse(readFileSync(undone)).features[0].properties.name,JSON.parse(readFileSync(input)).features[0].properties.name);
await command('redo-edit','--layer',layer);
await assert.rejects(command('set-attribute','--layer',layer,'--fid','0','--field','absent','--json',JSON.stringify('bad')),/existing field/i);
await assert.rejects(command('set-attribute','--layer',layer,'--fid','999','--field','name','--json',JSON.stringify('bad')),/not found/i);
await assert.rejects(command('set-attribute','--layer',layer,'--fid','0','--field','schemaVersion','--json','1.5'),/fractional/i);
await assert.rejects(command('set-attribute','--layer',layer,'--fid','0','--field','name','--json','{}'),/type/i);
await command('set-attribute','--layer',layer,'--fid','0','--field','schemaVersion','--json','3');
await command('set-attribute','--layer',layer,'--fid','0','--field','locked','--json','true');
await command('set-attribute','--layer',layer,'--fid','0','--field','source','--json','{\"schemaVersion\":1,\"sourceId\":\"map\",\"sequence\":9007199254740993}');
const page=await command('features','--layer',layer,'--limit','1','--geometry');
assert.equal(page.totalFeatures,'2');assert.equal(page.hasMore,true);assert.equal(page.features[0].fid,'0');
assert.equal(page.features[0].attributes.source.sequence,9007199254740993n);assert.match(page.features[0].geometryWkt,/^linestring/i);
const next=await command('features','--layer',layer,'--offset','1','--limit','1');
assert.equal(next.hasMore,false);assert.equal(next.features[0].fid,'1');
const selected=await command('features','--layer',layer,'--expression',`"name" = '편집 검증'`);
assert.equal(selected.features.length,1);assert.equal(selected.features[0].fid,'0');
await assert.rejects(command('features','--layer',layer,'--expression','"missing" = 1'),/expression/i);
const buffered=join(root,'buffered.geojson');await command('export','--layer',layer,'--output',buffered);
assert.equal(JSON.parse(readFileSync(buffered)).features[0].properties.name,'편집 검증');
assert.equal(JSON.parse(readFileSync(buffered)).features[0].properties.schemaVersion,3);
assert.equal(JSON.parse(readFileSync(buffered)).features[0].properties.locked,true);
assert.match(readFileSync(buffered,'utf8'),/9007199254740993/);
const oldGeometry=JSON.parse(readFileSync(input)).features[0].geometry;
const changedGeometry={type:'LineString',coordinates:[[127,37],[128.5,38.5]]};
await command('set-geometry','--layer',layer,'--fid','0','--wkt','LINESTRING (127 37, 128.5 38.5)');
const geometryOut=join(root,'geometry.geojson');await command('export','--layer',layer,'--output',geometryOut);
assert.deepEqual(JSON.parse(readFileSync(geometryOut)).features[0].geometry,changedGeometry);
await assert.rejects(command('set-geometry','--layer',layer,'--fid','0','--wkt','POINT (127 37)'),/geometry/i);
await assert.rejects(command('set-geometry','--layer',layer,'--fid','0','--wkt','LINESTRING (181 37, 182 38)'),/geographic/i);
await command('undo-edit','--layer',layer);
const undoGeometry=join(root,'geometry-undo.geojson');await command('export','--layer',layer,'--output',undoGeometry);
assert.deepEqual(JSON.parse(readFileSync(undoGeometry)).features[0].geometry,oldGeometry);
await command('redo-edit','--layer',layer);
const redoGeometry=join(root,'geometry-redo.geojson');await command('export','--layer',layer,'--output',redoGeometry);
assert.deepEqual(JSON.parse(readFileSync(redoGeometry)).features[0].geometry,changedGeometry);
assert.equal(digest(input),inputHash);
await command('rollback-edit','--layer',layer);
const rolled=join(root,'rolled.geojson');await command('export','--layer',layer,'--output',rolled);
assert.equal(JSON.parse(readFileSync(rolled)).features[0].properties.name,JSON.parse(readFileSync(input)).features[0].properties.name);
assert.deepEqual(JSON.parse(readFileSync(rolled)).features[0].properties.source,JSON.parse(readFileSync(input)).features[0].properties.source);
assert.deepEqual(JSON.parse(readFileSync(rolled)).features[0].geometry,oldGeometry);
assert.equal(digest(input),inputHash);assert.equal(digest(original),originalHash);
await assert.rejects(command('commit-edit','--layer',layer),/edit session/i);
await command('begin-edit','--layer',layer);
await command('set-attribute','--layer',layer,'--fid','0','--field','name','--json',JSON.stringify('committed'));
await command('commit-edit','--layer',layer);
assert.equal(JSON.parse(readFileSync(input)).features[0].properties.name,'committed');
assert.equal(digest(original),originalHash);
console.log(JSON.stringify({stage:'verified',root,pid:started.pid,geometry:true,undoRedo:true,rollback:true,commitOnTestCopy:true,originalPreserved:true}));
